# Regenerates test_vm_qvm.h: test_vm.c compiled to a QVM with the Quake III
# compiler tools (q3lcc and q3asm, built from the GPL ioquake3 source), and
# the results the same program gives compiled natively; and fake_ui_qvm.h,
# fake_ui.c, fake_game.c and fake_cgame.c compiled to QVMs. Only needed after changing the .c files; the
# tests use the committed headers.
#
#   Q3TOOLS=/path/to/folder/with/q3lcc/and/q3asm ./build.sh
set -eu
cd "$(dirname "$0")"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
"$Q3TOOLS/q3lcc" -DQ3_VM -S -Wf-target=bytecode -Wf-g -o "$tmp/test_vm.asm" test_vm.c
"$Q3TOOLS/q3asm" -o "$tmp/test_vm.qvm" "$tmp/test_vm.asm" syscalls.asm
cc -O1 -fwrapv -o "$tmp/native" test_vm.c native_main.c
{
    echo "// SPDX-License-Identifier: GPL-3.0-or-later"
    echo "// Copyright (C) 2026 The Reluva contributors"
    echo "// Generated by tests/data/qvm/build.sh from test_vm.c. Do not edit."
    echo "#pragma once"
    echo "#include <cstdint>"
    echo "static const uint8_t kTestVmQvm[] = {"
    od -An -v -tx1 "$tmp/test_vm.qvm" | sed 's/ \([0-9a-f][0-9a-f]\)/0x\1,/g; s/^/   /'
    echo "};"
    "$tmp/native"
} > test_vm_qvm.h
echo "wrote test_vm_qvm.h"

"$Q3TOOLS/q3lcc" -DQ3_VM -S -Wf-target=bytecode -Wf-g -o "$tmp/fake_ui.asm" fake_ui.c
"$Q3TOOLS/q3asm" -o "$tmp/fake_ui.qvm" "$tmp/fake_ui.asm" fake_ui.asm
{
    echo "// SPDX-License-Identifier: GPL-3.0-or-later"
    echo "// Copyright (C) 2026 The Reluva contributors"
    echo "// Generated by tests/data/qvm/build.sh from fake_ui.c. Do not edit."
    echo "#pragma once"
    echo "#include <cstdint>"
    echo "static const uint8_t kFakeUiQvm[] = {"
    od -An -v -tx1 "$tmp/fake_ui.qvm" | sed 's/ \([0-9a-f][0-9a-f]\)/0x\1,/g; s/^/   /'
    echo "};"
} > fake_ui_qvm.h
echo "wrote fake_ui_qvm.h"

"$Q3TOOLS/q3lcc" -DQ3_VM -S -Wf-target=bytecode -Wf-g -o "$tmp/fake_game.asm" fake_game.c
"$Q3TOOLS/q3asm" -o "$tmp/fake_game.qvm" "$tmp/fake_game.asm" fake_game.asm
{
    echo "// SPDX-License-Identifier: GPL-3.0-or-later"
    echo "// Copyright (C) 2026 The Reluva contributors"
    echo "// Generated by tests/data/qvm/build.sh from fake_game.c. Do not edit."
    echo "#pragma once"
    echo "#include <cstdint>"
    echo "static const uint8_t kFakeGameQvm[] = {"
    od -An -v -tx1 "$tmp/fake_game.qvm" | sed 's/ \([0-9a-f][0-9a-f]\)/0x\1,/g; s/^/   /'
    echo "};"
} > fake_game_qvm.h
echo "wrote fake_game_qvm.h"

"$Q3TOOLS/q3lcc" -DQ3_VM -S -Wf-target=bytecode -Wf-g -o "$tmp/fake_cgame.asm" fake_cgame.c
"$Q3TOOLS/q3asm" -o "$tmp/fake_cgame.qvm" "$tmp/fake_cgame.asm" fake_cgame.asm
{
    echo "// SPDX-License-Identifier: GPL-3.0-or-later"
    echo "// Copyright (C) 2026 The Reluva contributors"
    echo "// Generated by tests/data/qvm/build.sh from fake_cgame.c. Do not edit."
    echo "#pragma once"
    echo "#include <cstdint>"
    echo "static const uint8_t kFakeCgameQvm[] = {"
    od -An -v -tx1 "$tmp/fake_cgame.qvm" | sed 's/ \([0-9a-f][0-9a-f]\)/0x\1,/g; s/^/   /'
    echo "};"
} > fake_cgame_qvm.h
echo "wrote fake_cgame_qvm.h"
