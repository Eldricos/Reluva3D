#!/bin/sh
# Builds testdll.c as a 32-bit Windows DLL (x87 floating point, no SSE, as
# the late-1990s games' compilers made them) and writes it, with the results
# the same code gives built natively, to tests/data/x86_testdll.h.
# Needs clang, lld-link and llvm-dlltool (LLVM 15 or later).
set -e
here=$(cd "$(dirname "$0")" && pwd)
out="$here/../data/x86_testdll.h"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

printf 'LIBRARY KERNEL32.dll\nEXPORTS\nHeapAlloc@12\nGetProcessHeap@0\nGetVersion@0\n' > "$tmp/kernel32.def"
llvm-dlltool -m i386 -d "$tmp/kernel32.def" -l "$tmp/kernel32.lib" -k
clang --target=i686-pc-windows-msvc -march=pentium -mno-sse -O2 -fno-builtin -DTESTDLL_PE \
    -c "$here/testdll.c" -o "$tmp/testdll.obj"
lld-link /dll /entry:DllMain /nodefaultlib /base:0x10000000 /out:"$tmp/testdll.dll" "$tmp/testdll.obj" "$tmp/kernel32.lib"

cat > "$tmp/expect.c" <<'C'
#include <stdint.h>
#include <stdio.h>
uint32_t testdll_run(int which, uint32_t a, uint32_t b);
int testdll_count(void);
static const uint32_t inputs[][2] = {
    {0, 0}, {1, 1}, {7, 3}, {0xffffffffu, 2}, {0x80000000u, 0xffffffffu}, {123456789, 987654},
    {0xdeadbeef, 0x1234}, {42, 0x80000001u}, {1000, 0xfffffc18u}, {0x7fffffff, 31}, {19, 63}, {0xfffff000u, 17},
};
int main(void) {
    int n = (int)(sizeof inputs / sizeof inputs[0]);
    printf("static const uint32_t kX86TestInputs[][2] = {\n");
    for (int i = 0; i < n; ++i)
        printf("    {0x%08xu, 0x%08xu},\n", inputs[i][0], inputs[i][1]);
    printf("};\n// [test][input]: testdll_run's results built natively.\n");
    printf("static const uint32_t kX86TestExpected[%d][%d] = {\n", testdll_count(), n);
    for (int t = 0; t < testdll_count(); ++t) {
        printf("    {");
        for (int i = 0; i < n; ++i)
            printf("0x%08xu%s", testdll_run(t, inputs[i][0], inputs[i][1]), i + 1 < n ? ", " : "");
        printf("},\n");
    }
    printf("};\n");
    return 0;
}
C
cc -O2 -std=c99 -o "$tmp/expect" "$tmp/expect.c" "$here/testdll.c"

{
    echo "// Generated by tests/x86/build_testdll.sh from tests/x86/testdll.c; don't edit."
    echo "#pragma once"
    echo "#include <cstdint>"
    echo "static const unsigned char kX86TestDll[] = {"
    od -An -v -tx1 "$tmp/testdll.dll" | sed 's/ *\([0-9a-f][0-9a-f]\)/0x\1,/g; s/^/    /'
    echo "};"
    "$tmp/expect"
} > "$out"
echo "wrote $out ($(wc -c < "$tmp/testdll.dll") byte DLL)"
