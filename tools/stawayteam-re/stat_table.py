"""Write Reluva's table of Star Trek: Away Team's classes from the schema.

Reads the schema stat_classes.py writes
(docs/engines/stawayteam/research/classes.txt) and writes
src/engines/stawayteam/formats/class_table.cpp, which the engine reads the
game's binary objects with (formats/object_schema.h):

    python3 stat_table.py ../../docs/engines/stawayteam/research/classes.txt \\
        -o ../../src/engines/stawayteam/formats/class_table.cpp
"""

import argparse
import re

SAVED = {
    'int': 'kInt', 'ref': 'kRef', 'float': 'kFloat', 'bool': 'kBool', 'flag': 'kFlag',
    'point': 'kPoint', 'fpoint': 'kFloatPoint', 'double': 'kDouble', 'colour': 'kColour',
    'choice': 'kString', 'name': 'kString', 'string': 'kString', 'text': 'kString', 'ai': 'kString',
    'object': 'kObject', 'inline': 'kInline', 'objects': 'kObjects', 'array': 'kArray',
    'polygon': 'kPolygon', 'unknown': 'kUnknown',
}
# The classes whose own data the engine reads, by their writers
# (research/binary-objects.md); any other that has some can't be read.
OWN = {'-': 'kNone', '0x55b640': 'kSequence', '0x550ff0': 'kRotationSequence', '0x50f6e0': 'kModel',
       '0x52dad0': 'kWayPointMap', '0x5305e0': 'kWayPoint'}


def parse(path):
    classes = []
    for line in open(path):
        if line.startswith('class '):
            f = line.split()
            attrs = dict(x.split('=', 1) for x in f[2:])
            classes.append({'name': f[1], 'version': attrs['version'], 'parent': attrs['parent'],
                            'own': attrs['own-data'], 'size': attrs.get('size', 'None'), 'props': []})
        else:
            m = re.match(r'\s+"(.*)" (.*)$', line)
            if m:
                classes[-1]['props'].append((m.group(1), m.group(2).split()))
    return classes


def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('schema')
    ap.add_argument('-o', '--output', required=True)
    a = ap.parse_args()
    classes = sorted(parse(a.schema), key=lambda c: c['name'])
    index = {c['name']: i for i, c in enumerate(classes)}
    props = []
    rows = []
    for c in classes:
        first = len(props)
        for name, words in c['props']:
            kind = words[0]
            element = 'kUnknown'
            named = 'false'
            cls = -1
            size = 0
            for w in words[1:]:
                if w.startswith('class='):
                    cls = index.get(w[6:], -1)
                elif w.startswith('element='):
                    element = SAVED.get(w[8:], 'kUnknown')
                elif w.startswith('size='):
                    size = int(w[5:])
                elif w == 'named':
                    named = 'true'
            props.append('    {%s, Saved::%s, Saved::%s, %s, %d, %d},'
                         % (cstr(name), SAVED.get(kind.split(':')[0], 'kUnknown'), element, named, cls, size))
        own = OWN.get(c['own'], 'kOther')
        parent = index.get(c['parent'], -1)
        size = int(c['size']) if c['size'] != 'None' else 0
        version = float(c['version'])
        rows.append('    {%s, %rf, %d, OwnData::%s, %d, %d, %d},'
                    % (cstr(c['name']), version, parent, own, first, len(props) - first, size))
    with open(a.output, 'w', newline='\n') as out:
        out.write('''// SPDX-License-Identifier: GPL-3.0-or-later
// Copyright (C) 2026 The Reluva contributors

// Generated by tools/stawayteam-re/stat_table.py from
// docs/engines/stawayteam/research/classes.txt: the classes Star Trek.exe
// registers (US English retail), each with the properties it adds to its
// parent's, in order. Regenerate it rather than editing it.

#include "engines/stawayteam/formats/object_schema.h"

namespace reluva::stawayteam {

namespace {

const PropertySchema kProperties[] = {
''')
        out.write('\n'.join(props) + '\n};\n\n')
        out.write('// Sorted by name, for findClass.\nconst ClassSchema kClasses[] = {\n')
        out.write('\n'.join(rows) + '\n};\n\n} // namespace\n\n')
        out.write('''std::span<const ClassSchema> allClasses() {
    return kClasses;
}

std::span<const PropertySchema> allProperties() {
    return kProperties;
}

} // namespace reluva::stawayteam
''')
    print('%d classes, %d properties' % (len(classes), len(props)))


if __name__ == '__main__':
    main()
