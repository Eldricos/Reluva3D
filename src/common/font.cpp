// The glyphs as bits, one u8 per row (bit 4 the left column).
using Bitmap = std::array<uint8_t, kH>;
const std::array<Bitmap, 95>& bitmaps() {
    static const std::array<Bitmap, 95> table = [] {
        std::array<Bitmap, 95> t{};
        for (size_t g = 0; g < 95; ++g) {
            int row = 0, col = 0;
            for (const char* p = kGlyphs[g]; *p && row < kH; ++p) {
                if (*p == ' ') {
                    ++row, col = 0;
                    continue;
                }
                if (*p == '#' && col < kW)
                    t[g][size_t(row)] |= uint8_t(0x10 >> col);
                ++col;
            }
        }
        return t;
    }();
    return table;
}

// The ASCII character a code point is drawn as.
char asAscii(uint32_t cp) {
    cp = text::toLatin1(cp);
    if (cp >= 32 && cp < 127)
        return char(cp);
    switch (cp) {
    case 0xa0: return ' ';
    case 0xb4: return '\'';
    case 0xd7: return 'x';
    default: break;
    }
    // Latin-1 letters without their accents.
    static const char kLatin1[] = "AAAAAAACEEEEIIIIDNOOOOOxOUUUUYTsaaaaaaaceeeeiiiidnooooo/ouuuuyty";
    static_assert(sizeof kLatin1 == 0x40 + 1);
    if (cp >= 0xc0 && cp <= 0xff)
        return kLatin1[cp - 0xc0];
    return '?';
}

