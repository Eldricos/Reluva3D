#!/bin/sh
# Builds msvcp60.cpp as a 32-bit Windows DLL exporting what msvcp60.def
# lists (x87 floating point and no SSE, like the late-1990s games' own
# code) and writes it to msvcp60_dll.h, which Reluva embeds. Run it after
# changing either file. Needs clang, lld-link and llvm-dlltool (LLVM 15 or
# later).
set -e
here=$(cd "$(dirname "$0")" && pwd)
out="$here/msvcp60_dll.h"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# What it imports from MSVCRT.dll.
cat > "$tmp/msvcrt.def" <<'DEF'
LIBRARY MSVCRT.dll
EXPORTS
free
memcpy
memmove
memcmp
strlen
sprintf
fopen
fclose
fread
fwrite
fseek
ftell
fflush
fgetc
fputc
ungetc
fputs
abort
_iob DATA
??2@YAPAXI@Z
??3@YAXPAX@Z
DEF
llvm-dlltool -m i386 -d "$tmp/msvcrt.def" -l "$tmp/msvcrt.lib"

clang --target=i686-pc-windows-msvc -march=pentium -mno-sse -O2 -std=c++17 -ffreestanding -fno-builtin \
    -fno-exceptions -fno-rtti -fno-stack-protector -Wall -Wextra -Werror \
    -c "$here/msvcp60.cpp" -o "$tmp/msvcp60.obj"
lld-link /dll /entry:_DllMainCRTStartup /nodefaultlib /base:0x7c000000 /def:"$here/msvcp60.def" \
    /out:"$tmp/MSVCP60.dll" "$tmp/msvcp60.obj" "$tmp/msvcrt.lib"

{
    echo "// Generated by src/common/x86/runtime/build_msvcp60.sh from msvcp60.cpp and"
    echo "// msvcp60.def; don't edit."
    echo "#pragma once"
    echo "static const unsigned char kMsvcp60Dll[] = {"
    od -An -v -tx1 "$tmp/MSVCP60.dll" | sed -e 's/ *\([0-9a-f][0-9a-f]\)/0x\1,/g' -e 's/^/    /'
    echo "};"
} > "$out"
echo "Wrote $out ($(wc -c < "$tmp/MSVCP60.dll") bytes)"
