# Rebuilds glide_kernels.h from rasterize.comp: SPIR-V for Vulkan (with
# glslangValidator) and Metal source (with spirv-cross, its buffers renumbered
# as SDL's GPU API wants them for Metal: uniforms, read-only, read-write).
# Only needed after changing the shader; building Reluva uses the committed
# glide_kernels.h.
#
#   sudo apt install glslang-tools spirv-cross    # Debian/Ubuntu
set -eu
cd "$(dirname "$0")"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

glslangValidator -V --quiet rasterize.comp -o "$tmp/rasterize.spv"
spirv-cross --msl --msl-version 20000 "$tmp/rasterize.spv" --output "$tmp/rasterize.metal"
sed -i -e '/kernel void main0/{
s/\(constant Params& [A-Za-z0-9_]*\) \[\[buffer([0-9]*)\]\]/\1 [[buffer(0)]]/
s/\(const device Batch& [A-Za-z0-9_]*\) \[\[buffer([0-9]*)\]\]/\1 [[buffer(1)]]/
s/\(const device TexMem& [A-Za-z0-9_]*\) \[\[buffer([0-9]*)\]\]/\1 [[buffer(2)]]/
s/\(device Frame& [A-Za-z0-9_]*\) \[\[buffer([0-9]*)\]\]/\1 [[buffer(3)]]/
}' "$tmp/rasterize.metal"

out=glide_kernels.h
{
    echo "// SPDX-License-Identifier: GPL-3.0-or-later"
    echo "// Copyright (C) 2026 The Reluva contributors"
    echo "// Generated by build.sh from rasterize.comp. Do not edit."
    echo "#pragma once"
    echo "#include <cstddef>"
    echo "#include <cstdint>"
    echo "namespace reluva::glide::shaders {"
    echo "alignas(4) inline const uint8_t kRasterizeSpirv[] = {"
    od -An -v -tx1 "$tmp/rasterize.spv" | sed 's/ \([0-9a-f][0-9a-f]\)/0x\1,/g; s/^/   /'
    echo "};"
    # One literal per line: Visual Studio refuses literals over 16 KB.
    echo "inline const char kRasterizeMsl[] ="
    sed 's/^\(.*\)$/    R"msl(\1\n)msl"/' "$tmp/rasterize.metal"
    echo "    ;"
    echo "} // namespace reluva::glide::shaders"
} > "$tmp/$out"
mv "$tmp/$out" "$out"
echo "wrote $out"
