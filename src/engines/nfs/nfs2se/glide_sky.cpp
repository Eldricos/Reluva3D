GlideFog glideFog(int track, int roadPoint) {
    if (track < 0 || track >= static_cast<int>(std::size(kTrackFog)))
        return {};
    const TrackFog &f = kTrackFog[track];
    int table = 0;
    Rgb colour = f.colour;
    for (const Stretch &s : kStretches)
        if (s.track == track && s.from <= roadPoint) {
            table = s.table;
            colour = s.colour;
        }
    // Table i of 20 is i twentieths of the way from the first density to the last.
    return {f.first + static_cast<float>(table) * 0.05f * (f.last - f.first), colour};
}

std::array<Rgb, 17> skyRingColours(const Sky &sky) {
    std::array<Rgb, 17> out{};
    for (int k = 0; k < 8; ++k)
        for (int c = 0; c < 3; ++c) {
            const int sun = sky.skyBaseSun[size_t(c)];
            const int v = sun + (sky.skyBaseOpposite[size_t(c)] - sun) * k / 8;
            out[size_t(k)][size_t(c)] = v;
            out[size_t(15 - k)][size_t(c)] = v;
        }
    out[16] = out[0];
    return out;
}

