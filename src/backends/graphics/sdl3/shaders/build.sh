# Rebuilds compiled.h from the GLSL sources here: SPIR-V for Vulkan (with
# glslangValidator) and Metal source (with spirv-cross). Only needed after
# changing a shader; building Reluva uses the committed compiled.h.
#
#   sudo apt install glslang-tools spirv-cross    # Debian/Ubuntu
set -eu
cd "$(dirname "$0")"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

out=compiled.h
{
    echo "// SPDX-License-Identifier: GPL-3.0-or-later"
    echo "// Copyright (C) 2026 The Reluva contributors"
    echo "// Generated by build.sh from draw.vert and draw.frag. Do not edit."
    echo "#pragma once"
    echo "#include <cstddef>"
    echo "#include <cstdint>"
    echo "namespace reluva::shaders {"
} > "$tmp/$out"

for stage in vert frag; do
    glslangValidator -V --quiet "draw.$stage" -o "$tmp/draw.$stage.spv"
    spirv-cross --msl --msl-version 20000 "$tmp/draw.$stage.spv" --output "$tmp/draw.$stage.metal"
    name=$(echo "$stage" | sed 's/vert/Vertex/; s/frag/Fragment/')
    {
        echo "alignas(4) inline const uint8_t kDraw${name}Spirv[] = {"
        od -An -v -tx1 "$tmp/draw.$stage.spv" | sed 's/ \([0-9a-f][0-9a-f]\)/0x\1,/g; s/^/   /'
        echo "};"
        # One literal per line: Visual Studio refuses literals over 16 KB.
        echo "inline const char kDraw${name}Msl[] ="
        sed 's/^\(.*\)$/    R"msl(\1\n)msl"/' "$tmp/draw.$stage.metal"
        echo "    ;"
    } >> "$tmp/$out"
done
echo "} // namespace reluva::shaders" >> "$tmp/$out"
mv "$tmp/$out" "$out"
echo "wrote $out"
